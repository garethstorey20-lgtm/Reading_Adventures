/**
 * Builds a ready-to-upload folder for GitHub Pages.
 * Output: Desktop\reading-adventures-web
 */
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const TRACKER = path.join(__dirname, "..", "..");
const PILOT = path.join(TRACKER, "web-pilot");
const OUT = path.join(
  process.env.USERPROFILE || "",
  "OneDrive",
  "Desktop",
  "reading-adventures-web"
);

function rimraf(dir) {
  if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true });
}

function copyFile(src, dest) {
  if (!fs.existsSync(src)) {
    console.warn("skip (missing):", src);
    return false;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  return true;
}

function copyDir(src, dest) {
  if (!fs.existsSync(src)) {
    console.warn("skip (missing dir):", src);
    return;
  }
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else copyFile(s, d);
  }
}

console.log("Syncing web-pilot from ReadingAdventures V1.html...");
execSync("node scripts/sync-from-v1.cjs", { cwd: PILOT, stdio: "inherit" });

console.log("\nBuilding folder:", OUT);
